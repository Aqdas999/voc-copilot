def main() -> None:
    df = pd.DataFrame(TICKETS, columns=["date", "language", "category", "text"])
    # stable sort: same-date tickets keep their written order, so IDs never shuffle between runs
    df = df.sort_values("date", ascending=False, kind="stable").reset_index(drop=True)

    # Unified schema from CLAUDE.md — clearly labeled synthetic.
    df["id"] = [f"SYN-{i:04d}" for i in range(1, len(df) + 1)]
    df["source"] = "synthetic_ticket"
    df["rating"] = ""   # support tickets have no star rating
    df["url"] = ""      # no public link for synthetic data
    df = df[["id", "source", "date", "rating", "text", "url", "language"]]  # category dropped

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUTPUT_PATH, index=False, encoding="utf-8-sig")
    print(f"Saved {len(df)} synthetic tickets to {OUTPUT_PATH}")
    print(df["language"].value_counts().to_string())


if __name__ == "__main__":
    main()
